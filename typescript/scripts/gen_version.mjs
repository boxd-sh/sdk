#!/usr/bin/env node
// Regenerate `src/_version.ts` from `package.json`'s `version` field.
//
// `VERSION` used to be read at the CONSUMER's runtime via
// `createRequire(import.meta.url)("../package.json")` — that needs
// `node:module` and filesystem access, neither of which exist in a
// Cloudflare Worker (the `@boxd-sh/sdk/web` entry). Baking the version
// into a plain source file at SDK build time removes that dependency
// entirely: the published `dist/_version.js` is just a string literal.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const sdkDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(readFileSync(path.join(sdkDir, "package.json"), "utf8"));

const out = `// Generated by scripts/gen_version.mjs from package.json. DO NOT EDIT.
export const VERSION: string = ${JSON.stringify(pkg.version)};
`;
writeFileSync(path.join(sdkDir, "src", "_version.ts"), out);
console.log(`src/_version.ts <- version ${pkg.version}`);
